#!/usr/bin/env python3
"""Generate apps/splat-lab-lgm.yaml (home-k8s) from the scripts in this folder.

The k8s file must contain the Job's scripts inline (ConfigMap), so it is *generated* rather than
hand-maintained: run this after editing anything here and commit both repos.

    python3 tools/splats/g1/gen-manifest.py > /home/david/dev/home-k8s/apps/splat-lab-lgm.yaml
    JOB_N=2 python3 tools/splats/g1/gen-manifest.py > ...      # bump the Job name to re-run

Jobs are immutable: each re-run gets `splat-lab-lgm-<JOB_N>` and the previous Job block is
replaced in the same commit (Flux prunes the old Job; a TTL would make Flux re-create and re-run it).
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = "github.com/dbirks/aise-nov-2026-local-llms"

FILES = [
    # ↑ everything the Job needs, and only that. tools/splats/g1/normalize.py and pack.sh are NOT
    # listed: they run on the workstation after `kubectl cp`, which is where the .spz assets are made.
    "run.sh",
    "requirements.txt",
    "inputs.json",
    "mvgen.py",
    "lgm2ply.py",
    "fetch_inputs.py",
    "selftest.py",
    "report.py",
    "vendor/kiui/__init__.py",
    "vendor/kiui/cam.py",
    "vendor/kiui/op.py",
    "vendor/kiui/lpips.py",
    "vendor/xformers/__init__.py",
    "vendor/xformers/ops/__init__.py",
    "vendor/diff_gaussian_rasterization/__init__.py",
]

IMAGE = ("pytorch/pytorch:2.7.1-cuda12.6-cudnn9-runtime"
         "@sha256:2b59b1b91885677814f78be1f8df48a25d5dc952eb6580eaecfefca510f9afd3")
LGM_COMMIT = "fe8d12cff8c827df7bb77a3c8e8b37408cb6fe4c"


def key(rel: str) -> str:
    """ConfigMap key for a repo-relative script. Deliberately FLAT: kubelet does not create
    sub-directories for ConfigMap volume items (splat-lab-lgm-1 mounted an empty vendor/kiui), so
    run.sh rebuilds the vendor/<pkg>/<mod>.py tree from these names."""
    return rel.replace("/", "-")


def block(rel: str) -> str:
    with open(os.path.join(HERE, rel), encoding="utf-8") as f:
        body = f.read().rstrip("\n")
    # 4-space indent: block-scalar content must be indented deeper than its key (2 spaces).
    indented = "\n".join(("    " + line) if line.strip() else "" for line in body.split("\n"))
    return f"  {key(rel)}: |-\n{indented}\n"


def main() -> int:
    job_n = os.environ.get("JOB_N", sys.argv[1] if len(sys.argv) > 1 else "1")
    sizes = {rel: len(open(os.path.join(HERE, rel), encoding="utf-8").read()) for rel in FILES}
    total = sum(sizes.values())

    out = [f"""# splat-lab G1 ({LGM_COMMIT[:9]}) — LGM (Large Multi-View Gaussian Model, ECCV 2024) on dave-droid's
# GTX 1070, for the AISE Nov 2026 deck (github.com/dbirks/aise-nov-2026-local-llms, public/splats/g1/).
# GENERATED by tools/splats/g1/gen-manifest.py from tools/splats/g1/* — edit those, not this file.
#
# Pipeline per subject: source picture (PD/CC0, Wikimedia Commons; sha256 + credit in the ConfigMap's
# inputs.json) -> rembg cut-out -> ImageDream "ipmv" multi-view diffusion (fp16, 30 steps, guidance
# 5.0, seed 42, elevation 0) -> LGM `big` U-Net -> 4 x 128^2 = 65,536 Gaussians -> .ply in /data/out.
#
# Why it is split the way it is:
#   * ImageDream's fp16 weights (~3.8 GB) and LGM's (~0.8 GB) must never be resident together: HAMi
#     caps this container at 5000 MiB (~4.9 GiB) of the 1070's 8 GB. mvgen and lgm2ply are separate
#     processes; the CLIP-ViT-H image encoder is also dropped back to CPU after one forward.
#   * No CUDA extension is compiled: diff-gaussian-rasterization and xformers are replaced by
#     vendored stubs/SDPA adapters in the ConfigMap (Pascal sm_61 has no xformers kernels, and the
#     -devel image + nvcc are not needed if we never render). The .ply is the deliverable.
#   * pytorch 2.7.1 + cu126 (not CUDA 13 — Pascal is gone there); the runtime tag is enough.
#
# Re-run: bump JOB_N (Jobs are immutable) and delete the old Job block in the same commit.
# Results: kubectl cp default/<splat-lab-files pod>:/data/out/g1-<JOB_N> ./out   (see public/splats/g1/README.md)
# Sizes: {total // 1024} KiB of scripts in one ConfigMap (limit 3 MiB). Keys are flat (vendor-kiui-cam.py);
# run.sh rebuilds the package tree — see key() below.
---
apiVersion: v1
kind: ConfigMap
metadata:
  name: splat-lab-lgm-scripts
  namespace: default
  labels:
    app.kubernetes.io/part-of: splat-lab
data:
"""]

    for rel in FILES:
        out.append(block(rel))

    out.append(f"""---
apiVersion: batch/v1
kind: Job
metadata:
  name: splat-lab-lgm-{job_n}
  namespace: default
  labels:
    app.kubernetes.io/part-of: splat-lab
    splat-lab/method: lgm
spec:
  backoffLimit: 0
  activeDeadlineSeconds: 10800
  template:
    metadata:
      labels:
        app.kubernetes.io/part-of: splat-lab
        splat-lab/method: lgm
    spec:
      restartPolicy: Never
      runtimeClassName: nvidia
      nodeSelector: {{ kubernetes.io/hostname: dave-droid }}
      tolerations:
        - {{ key: dedicated, operator: Equal, value: pascal, effect: NoSchedule }}
      containers:
        - name: run
          image: {IMAGE}
          command: [bash, /scripts/run.sh, all]
          env:
            - {{ name: OUT, value: /data/out/g1-{job_n} }}
            - {{ name: SCRIPTS, value: /scripts }}
            - {{ name: IMAGE, value: "{IMAGE}" }}
            - {{ name: LGM_REV, value: "{LGM_COMMIT}" }}
            - {{ name: HF_HOME, value: /data/cache/hf }}
            - {{ name: U2NET_HOME, value: /data/cache/u2net }}
            - {{ name: NODE_NAME, valueFrom: {{ fieldRef: {{ fieldPath: spec.nodeName }} }} }}
          resources:
            requests: {{ cpu: "2", memory: 8Gi }}
            limits: {{ cpu: "6", memory: 24Gi, nvidia.com/gpu: "1", nvidia.com/gpumem: "5000" }}
          volumeMounts:
            - {{ name: data, mountPath: /data }}
            - {{ name: scripts, mountPath: /scripts, readOnly: true }}
      volumes:
        - {{ name: data, persistentVolumeClaim: {{ claimName: splat-lab-data }} }}
        # whole-ConfigMap mount (no `items:` — nested item paths are not materialised); all keys
        # are flat file names, see key() in tools/splats/g1/gen-manifest.py
        - {{ name: scripts, configMap: {{ name: splat-lab-lgm-scripts, defaultMode: 420 }} }}
""")
    sys.stdout.write("\n".join(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
